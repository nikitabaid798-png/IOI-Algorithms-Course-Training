# ---- Set Intersection ----

# Create two sets
class_a = {"Math", "Science", "English", "Computer"}
class_b = {"Science", "Computer", "History", "Art"}

print("Class A subjects:", class_a)
print("Class B subjects:", class_b)

# Intersection of two sets
common_subjects = class_a.intersection(class_b)

print("\nCommon subjects:", common_subjects)
